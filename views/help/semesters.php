<h3>What this page is for</h3>
<p>The semesters of your school. Everyone works on the active semester. Rooms, levels, lecturers and periods are shared by all semesters; courses belong to one.</p>
<h3>How to use it</h3>
<ol>
  <li>To start a new semester, create it, then press Set active.</li>
  <li>Use Copy courses here to bring last semester's courses across.</li>
</ol>
<h3>What the fields mean</h3>
<dl>
  <dt>Session</dt><dd>Two years with a slash, for example 2025/2026.</dd>
  <dt>Teaching dates (optional)</dt><dd>When the semester starts and how long it runs, until a date or for a number of weeks. Used by the Month view and the dated export. You can set them later under Dates and holidays.</dd>
</dl>
<h3>Common mistakes</h3>
<ul>
  <li>Forgetting to set the new semester active, so everyone keeps working on the old one.</li>
</ul>
