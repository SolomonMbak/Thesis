<h3>What this page is for</h3>
<p>The dashboard is the summary of your school: how far setup has got, how much data you have, whether the data is ready, the latest run and what is published. Warnings at the top say what needs attention and what to do.</p>
<h3>How to use it</h3>
<ol>
  <li>Read any warnings first and follow what they say.</li>
  <li>Click a number (for example Rooms) to open that list.</li>
  <li>Use the Setup Guide panel to continue setting up.</li>
</ol>
<h3>What the fields mean</h3>
<dl>
  <dt>Class sessions</dt><dd>The individual classes the timetable has to place each week, worked out from your courses.</dd>
  <dt>Open periods</dt><dd>Teaching periods in the week that are not blocked.</dd>
</dl>
<h3>Common mistakes</h3>
<ul>
  <li>Thinking a run failed when it is only waiting: runs from all schools take turns; the run page shows your place in the queue.</li>
</ul>
