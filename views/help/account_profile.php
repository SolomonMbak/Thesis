<h3>What this page is for</h3>
<p>Your own account: your name, theme, password, two-step sign-in and the browsers where you stay signed in. It works in every school you belong to.</p>
<h3>How to use it</h3>
<ol>
  <li>Change your name or theme and press Save.</li>
  <li>To change your password, type the current one, then the new one twice. Other browsers where you stayed signed in must sign in again.</li>
  <li>Press Set up two-step sign-in to protect your account with a code from your phone. Recommended for owners and administrators.</li>
  <li>Lost a phone or used a shared computer? Press Sign out on all browsers.</li>
</ol>
<h3>What the fields mean</h3>
<dl>
  <dt>Theme</dt><dd>System follows your device; Light and Dark always use that look.</dd>
  <dt>Where you stay signed in</dt><dd>Browsers where you ticked "Keep me signed in". Each lasts up to 30 days from that sign-in, or until you sign out there.</dd>
</dl>
