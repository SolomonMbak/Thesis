<h3>What this page is for</h3>
<p>Settings that affect the whole school: the public link name, the default search settings, deleting old runs and, for the owner, handing over or deleting the school.</p>
<h3>How to use it</h3>
<ol>
  <li>Change the link name only before you share the link, or tell people the new one.</li>
  <li>Delete old runs to keep the list short; published runs are always kept.</li>
</ol>
<h3>What the fields mean</h3>
<dl>
  <dt>Default search settings</dt><dd>Fill in the Generate page. The usual values suit most departments.</dd>
</dl>
<h3>Common mistakes</h3>
<ul>
  <li>Deleting the school by mistake: you must type its link name first, and it cannot be undone.</li>
</ul>
