<h3>What this page is for</h3>
<p>Shows how your courses are split into the individual classes the timetable places each week. This happens automatically; the page is here so you can see it.</p>
<h3>How to use it</h3>
<ol>
  <li>Check that each course has the classes you expect, for example 1 + 1 + 1 for a 3-hour lecture.</li>
  <li>If a split is wrong, change the course (hours, Practical, 2-hour block).</li>
</ol>
<h3>What the fields mean</h3>
<dl>
  <dt>Classes (hours each)</dt><dd>Each number is one class; 2 or 3 means a block of consecutive hours.</dd>
</dl>
